# Bivariate mixing distributions for joint mean, variance
#########

class MixingDistribution(ABC):
    """Base class for bivariate mixing distributions of mean and variance"""
    @abstractmethod
    def generate_mean_and_variance(self, rng, n) -> tuple:
        """Return tuple of arrays (mean, variance) sampled
        from the mixing distribution.
        Each array has n draws of the distribution."""

    @abstractmethod
    def mean_and_variance_joint_approx_pmf(self) -> tuple:
        # This docstring was AI-generated
        """
        Exact/approximate joint pmf over (mean, variance) support points.

        Returns
        -------
        tuple (means, variances, weights) where each is a 1-D array of the same
        length; the k-th entry (means[k], variances[k]) is a joint support point
        carrying probability mass weights[k]. This is a randomness-free
        representation used for analytic computations (e.g. the oracle Bayes
        rule / Tweedie formula).
        """

class MixIndependentMeanVariance(MixingDistribution):
    """Class for when mean and variance are independent"""
    def __init__(self,
                 mean_distribution: SingleVariableDistribution,
                 var_distribution: SingleVariableDistribution):
        self.mean_distribution = mean_distribution
        self.var_distribution = var_distribution

    def generate_mean_and_variance(self, rng, n):
        return (self.mean_distribution.generate(rng, n), self.var_distribution.generate(rng, n))

    def mean_and_variance_joint_approx_pmf(self):
        # This method was AI-generated
        # Independent mean/variance => joint pmf is the outer product of the
        # two marginal pmfs, flattened to a list of joint support points.
        mean_support, mean_weights = self.mean_distribution.approx_pmf()
        var_support, var_weights = self.var_distribution.approx_pmf()

        mean_support = np.asarray(mean_support)
        var_support = np.asarray(var_support)

        means = np.repeat(mean_support, len(var_support))
        variances = np.tile(var_support, len(mean_support))
        weights = np.outer(mean_weights, var_weights).ravel()

        return means, variances, weights


class MixJointMeanVariance(MixingDistribution):
    """
    General (possibly correlated) discrete joint distribution H(alpha, theta).

    The joint mixing distribution is specified directly as a list of joint
    support points (means[k], variances[k]) each carrying probability mass
    weights[k]. This covers the case where mean and variance are NOT
    independent (the independent case is just the special case where the
    weights factor as an outer product).

    Parameters
    ----------
    means : array-like, shape (K,)
        alpha-coordinate of each joint support point.
    variances : array-like, shape (K,)
        theta-coordinate of each joint support point. Must be strictly
        positive.
    weights : array-like, shape (K,)
        Probability mass on each support point; must be nonnegative and sum
        to 1.
    """
    
    def __init__(self, means, variances, weights):
        self.means = np.asarray(means, dtype=float)
        self.variances = np.asarray(variances, dtype=float)
        self.weights = np.asarray(weights, dtype=float)

        if not (self.means.shape == self.variances.shape == self.weights.shape):
            raise ValueError(
                "means, variances, weights must share the same shape; got "
                f"{self.means.shape}, {self.variances.shape}, {self.weights.shape}"
            )
        if self.means.ndim != 1:
            raise ValueError("means, variances, weights must be 1-D arrays")
        if np.any(self.variances <= 0):
            raise ValueError("all variances (theta) must be strictly positive")
        if np.any(self.weights < 0):
            raise ValueError("weights must be nonnegative")
        if not np.isclose(np.sum(self.weights), 1):
            raise ValueError(f"weights must sum to 1; got {np.sum(self.weights)}")

    def generate_mean_and_variance(self, rng, n):
        # Inverse-CDF sampling over the joint support (single uniform stream,
        # one draw per unit, so a correlated (alpha, theta) pair is drawn
        # jointly rather than from two independent streams).
        u = rng.uniform(0, 1, size=n)
        cumulative = np.cumsum(self.weights)
        indices = np.searchsorted(cumulative, u, side="right")
        indices = np.clip(indices, 0, len(self.weights) - 1)
        return self.means[indices], self.variances[indices]

    def mean_and_variance_joint_approx_pmf(self):
        return self.means, self.variances, self.weights


class GaussianMixture:
    """Gaussian mixture of a mixing distribution"""
    def __init__(self,
                 mixing_distribution: MixingDistribution):
        self.mixing_distribution = mixing_distribution

    def generate(self, rng, n, m, return_latents=False):
        """return an (n, m) array: n units, each with m draws from a Gaussian
        whose (mean, variance) is a single draw from the mixing distribution.

        Each unit i draws one (alpha_i, theta_i); its m observations are
        alpha_i + sqrt(theta_i) * N(0, 1). mean/variance are length-n, so they
        broadcast over the m columns via an added trailing axis.

        If return_latents is True, also return the per-unit latent (alpha,
        theta) that generated the data, as (y, alpha, theta) with alpha, theta
        of shape (n,). This is needed by metrics that compare an estimate of
        alpha to the true latent alpha.
        """
        mean, variance = self.mixing_distribution.generate_mean_and_variance(rng, n)

        mean = np.asarray(mean).reshape(n, 1)
        variance = np.asarray(variance).reshape(n, 1)

        y = mean + np.sqrt(variance) * rng.normal(0, 1, (n, m))

        if return_latents:
            return y, mean.reshape(n), variance.reshape(n)
        return y