"""
Data Generator for the Gaussian location-scale mixture model

Gaussian mixtures are generated by first sampling from some
base distribution for their mean (alpha) and variance (theta),
and then their outpus is a sample of N(alpha, theta).

Although in theory we could consider a joint distribution for
the mean and variance, the paper considers the case when alpha
is independent of theta, so that is what we do here (but the
framework will be extensible to the general case)
"""


from abc import ABC, abstractmethod

import numpy as np

class SingleVariableDistribution(ABC):
    """Single-variable distributions (for generating mean, variance independently)"""
    # Intentionally different base class and generate method
    #  from joint mixing distribution because I wanted some
    #  cues about which type of object is being generated
    @abstractmethod
    def generate(self, rng, n):
        """Sample from the distribution n times."""

    @abstractmethod
    def approx_pmf(self):
        """
        An approximate pmf (exact if discrete or uniform)
            for differentiation purposes
        """

class DiscreteDistribution(SingleVariableDistribution):
    """Discrete distribution on support_points with corresponding weights"""
    def __init__(self,
                 support_points,
                 weights):
        self.support_points = np.asarray(support_points)
        self.weights = np.asarray(weights)
        if not np.isclose(np.sum(self.weights), 1):
            raise Warning(f"weights should sum to 1. weights={self.weights}")
        if not np.shape(self.weights)==np.shape(self.support_points):
            raise Warning(f"support_points and weights should have same shape. shape(support, weights)={self.support_points.shape}, {self.weights.shape}")
    
    def generate(self, rng, n):
        # Fixed this method with AI
        # Inverse-CDF sampling from the discrete distribution
        u = rng.uniform(0, 1, size=n)
        cumulative = np.cumsum(self.weights)
        indices = np.searchsorted(cumulative, u, side="right")
        indices = np.clip(indices, 0, len(self.support_points) - 1)
        return self.support_points[indices]

    def approx_pmf(self):
        """
        (support_points, weights) representation of the distribution, for Tweedie's formula
        """
        return self.support_points, self.weights

class UniformDistribution(SingleVariableDistribution):
    """Keeping future extensibility to other distributions open"""
    def __init__(self):
        raise NotImplementedError
    def generate(self):
        raise NotImplementedError



